<h2>Anleitung</h2>
<p>Sobald jemand eine L&ouml;sung gefunden hat, bleiben 60 Sekunden, um eine k&uuml;rzere zu finden.
Die k&uuml;rzeste L&ouml;sung gewinnt das Ziel, bei gleicher L&auml;nge die zuerst gefundene, und die Roboter bleiben dort stehen, wo sie sie hinterlassen hat.
Nach 17 Zielen ist das Spiel zu Ende.</p>
<p>Gewertet werden die gewonnenen Ziele, bei Gleichstand die Z&uuml;ge, und weniger sind besser:
Wer ein Ziel gewinnt, bekommt die Z&uuml;ge seiner L&ouml;sung, alle anderen die der l&auml;ngsten gefundenen L&ouml;sung plus zehn.</p>
<p>Du kannst Mitspieler einladen, indem du die Spiel-URL oder den Spielcode mit ihnen teilst.
Bricht die Verbindung zum Server ab, l&auml;uft das Spiel allein weiter.</p>
<p>Oben links l&auml;uft der Countdown, oben rechts stehen Runde, gewonnene Ziele und Z&uuml;ge.
Links liegt das Spielfeld, rechts stehen deine L&ouml;sungen: unten die aktuelle, oben die beste, dazwischen alle bisherigen.</p>
<h3>Mit der Maus</h3>
<ul>
	<li>&Uuml;ber einen Roboter fahren zeigt seine m&ouml;glichen Z&uuml;ge.</li>
	<li>Ein Klick auf einen Roboter w&auml;hlt ihn aus.</li>
	<li>Ein Klick auf einen der blassen Roboter an den Endpunkten zieht ihn dorthin.</li>
	<li>Ein Klick auf ein leeres Feld hebt die Auswahl auf.</li>
	<li>Die Kn&ouml;pfe unten rechts im L&ouml;sungsfenster nehmen den letzten oder alle Z&uuml;ge zur&uuml;ck.</li>
</ul>
<h3>Mit der Tastatur</h3>
<ul>
	<li>1 bis 5 w&auml;hlt einen Roboter, 0 hebt die Auswahl auf.</li>
	<li>Die Pfeiltasten ziehen den gew&auml;hlten Roboter.</li>
	<li>Die R&uuml;cktaste nimmt den letzten Zug zur&uuml;ck.</li>
	<li>Escape nimmt alle Z&uuml;ge zur&uuml;ck.</li>
</ul>
